import {strict as assert} from "node:assert";
import {readFileSync} from "node:fs";
import {PAPER_MOODS,PAPER_RULES,paperAppearance,validPaperMood,validPaperRule} from "../src/lib/note-paper";
import {noteCaretColor} from "../src/lib/note-caret-color";
assert.equal(PAPER_MOODS.length,6);
assert.equal(PAPER_RULES.length,5);
assert.ok(validPaperMood("mist"));
assert.ok(!validPaperMood("malicious"));
assert.ok(validPaperRule("grid"));
assert.ok(paperAppearance("mist","lined").backgroundImage?.includes("repeating-linear-gradient"));
assert.ok(paperAppearance("sage","grid").backgroundImage?.includes("linear-gradient"));
assert.ok(paperAppearance("solid","plain").backgroundImage===undefined);
const e=readFileSync("src/routes/editor.$id.tsx","utf8");
assert.ok(e.includes('aria-label="Оформление листа"'));
assert.ok(e.includes('aria-label="Разметка бумаги"'));
assert.ok(e.includes('setPaperMood("solid")'));
assert.ok(e.includes("paperAppearance(paperMood,paperRule,canvasBg)"));
assert.ok(e.includes("style: { background: canvasBg, paperMood, paperRule }"));
console.log("Separated note background and paper ruling persistence checks passed.");

assert.ok(validPaperMood("lavender"));
assert.ok(validPaperRule("margin"));
assert.ok(PAPER_MOODS.some(m=>m.id==="lavender"&&m.background.startsWith("#")));
assert.ok(PAPER_RULES.some(r=>r.id==="margin"));
const notebook=paperAppearance("lavender","margin");
assert.ok(notebook.backgroundImage?.includes("repeating-linear-gradient"),"Ruled lines remain visible");
assert.ok(notebook.backgroundImage?.includes("216,79,90"),"Red notebook margin is rendered");
assert.ok(notebook.backgroundImage?.includes("radial-gradient"),"Pastel mood is layered underneath ruling");
assert.equal(paperAppearance("solid","plain").backgroundImage,undefined);

assert.equal(noteCaretColor("#FDE68A"),"#000000","Yellow paper uses a black caret");
assert.equal(noteCaretColor("#18181B"),"#FFFFFF","Dark paper uses a white caret");
assert.equal(noteCaretColor("#ffffff"),"#000000");
const editorSource=readFileSync("src/routes/editor.$id.tsx","utf8");
const styleSource=readFileSync("src/styles.css","utf8");
assert.ok(editorSource.includes('"--wave-note-caret": noteCaretColor(canvasBg)'));
assert.ok(styleSource.includes('.sn-tiptap [contenteditable="true"]'));
assert.ok(styleSource.includes('caret-color: var(--wave-note-caret,#000000)'));

const lightGrid=paperAppearance("solid","grid","#FDE68A");
const darkGrid=paperAppearance("solid","grid","#111827");
assert.ok(lightGrid.backgroundImage?.includes("66,84,112"));
assert.ok(darkGrid.backgroundImage?.includes("226,232,240"));
assert.equal(darkGrid.backgroundSize,"24px 24px,24px 24px");
assert.ok(paperAppearance("solid","dots","#111827").backgroundImage?.includes("226,232,240"));
assert.ok(paperAppearance("solid","lined","#111827").backgroundImage?.includes("226,232,240"));
assert.ok(paperAppearance("solid","margin","#111827").backgroundImage?.includes("251,113,133"));
assert.equal(paperAppearance("solid","plain","#111827").backgroundImage,undefined);
assert.ok(paperAppearance("lavender","margin").backgroundImage?.includes("216,79,90"));
