import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = (path: string) => readFileSync(path, "utf8");
const code = read("src/capacitor-client.tsx");
const shell = read("scripts/write-capacitor-index.mjs");
const theme = read("android-overlay/app/src/main/res/values/styles.xml");
const resource = read("android-overlay/app/src/main/res/drawable/wave_splash_logo.xml");
const blank = read("android-overlay/app/src/main/res/drawable/wave_splash_blank.xml");
const config = JSON.parse(read("capacitor.config.json"));
assert.match(theme, /windowSplashScreenAnimatedIcon">@drawable\/wave_splash_blank/);
assert.match(blank, /android:fillColor="#00000000"/);
assert.match(resource, /<vector/);
assert.match(resource, /android:pathData=/);
assert.match(shell, /Tengrize Studio/);
assert.match(shell, /WAVE NOTES/);
assert.match(shell, /fill: #fff; opacity: 0;/);
assert.match(shell, /wave-halo/);
assert.match(shell, /wave-atmosphere/);
const splashCss = shell.slice(shell.indexOf('<style id="wave-intro-style">'), shell.indexOf('</style>', shell.indexOf('<style id="wave-intro-style">'))).replace(/\/\*[\s\S]*?\*\//g, "");
assert.doesNotMatch(splashCss, /(?:^|[^-])filter\s*:|clip-path\s*:|stroke-dash(?:array|offset)\s*:|text-shadow\s*:/,
  "Cold-start animation must not use expensive blur/clipping/vector-dash effects");
assert.match(shell, /@media \(prefers-reduced-motion: reduce\)/);
assert.match(shell, /window\.__waveNotesIntro/);
assert.match(shell, /5200/);
assert.match(shell, /4210 - \(Date\.now\(\) - born\)/);
assert.match(shell, /requestAnimationFrame\(begin\)/);
assert.match(shell, /if \(started \|\| closed\) return/);
assert.match(shell, /wave-mark-arrive/);
assert.match(shell, /wave-contour/);
assert.match(shell, /wave-words \.78s ease-out 1\.73s/);
assert.match(shell, /wave-words \.78s ease-out 2\.08s/);
assert.match(shell, /position: absolute; inset: 0; opacity: 0; pointer-events: none/);
assert.match(shell, /Replace the visible circular halo with broad, barely visible fog/);
assert.match(shell, /appHasPainted\(\)/);
assert.match(shell, /childElementCount/);
assert.match(shell, /4900/);
assert.match(shell, /aria-hidden="true"/);
assert.match(code, /hideNativeSplash\(\)\.finally\(beginIntro\)/);
assert.match(code, /finishIntro\(\)/);
assert.equal(config.plugins.SplashScreen.androidSplashResourceName, "wave_splash_blank");
assert.ok(config.plugins.SplashScreen.launchShowDuration <= 350);
assert.ok(config.plugins.SplashScreen.launchFadeOutDuration <= 120);
assert.doesNotMatch(splashCss, /animation:\s*wave-light\s/, "Legacy strip light must not return");
assert.match(shell, /M199,1 C212,1 223,12 223,25/);
assert.match(resource, /M199,1 C212,1 223,12 223,25/);
assert.doesNotMatch(splashCss, /border-radius:\s*50%/, "Visible round bloom must not return");
assert.match(splashCss, /radial-gradient\(ellipse 105% 78%/);
console.log("Studio intro: low-energy fog, no circular halo, immediate motion and smooth app handoff.");
