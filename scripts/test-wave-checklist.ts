import {strict as assert} from "node:assert";
import {readFileSync} from "node:fs";
import {WaveChecklistItem} from "../src/lib/wave-checklist";
const schema=WaveChecklistItem.config;
assert.equal(schema.name,"waveChecklistItem");
assert.equal(schema.group,"block");
assert.equal(schema.content,"inline*");
const ext=readFileSync("src/lib/wave-checklist.ts","utf8");
assert.ok(ext.includes('data-type="wave-check-item"'));
assert.ok(ext.includes("editor.view.state.tr.setNodeMarkup(pos,undefined"));
assert.ok(ext.includes('data-done'));
const editor=readFileSync("src/routes/editor.$id.tsx","utf8");
assert.ok(editor.includes("WaveChecklistItem,"));
assert.ok(editor.includes('aria-label="Добавить список дел"'));
assert.ok(editor.includes('shape:"circle"'));
assert.ok(editor.includes('shape:"square"'));
assert.ok(editor.includes('shape:"diamond"'));
assert.ok(editor.includes('shape:"check"'));
assert.ok(editor.includes("onClick={handleSave}"));
console.log("Editable checklist schema, four shapes and persistence wiring checked");
