import {strict as assert} from "node:assert";
import {readFileSync} from "node:fs";
import {findWords} from "../src/lib/in-note-search";
import {Schema} from "@tiptap/pm/model";
const schema=new Schema({nodes:{doc:{content:"block+"},paragraph:{content:"text*",group:"block",toDOM:()=>["p",0],parseDOM:[{tag:"p"}]},text:{group:"inline"}}});
const doc=schema.nodes.doc.create(null,[schema.nodes.paragraph.create(null,[schema.text("встреча завтра, встреча послезавтра")])]);
assert.equal(findWords(doc,"встреча").length,2);
assert.equal(findWords(doc,"ВСТРЕЧА").length,2);
assert.equal(findWords(doc,"ВСТРЕЧА",true).length,0);
const i=readFileSync("src/routes/index.tsx","utf8");
assert.ok(i.includes('aria-expanded={expanded === "view"}'));
assert.ok(i.includes('aria-expanded={expanded === "sort"}'));
assert.ok(i.includes('setExpanded(v => v === "view" ? null : "view")'));
assert.ok(i.includes('setExpanded(v => v === "sort" ? null : "sort")'));
const e=readFileSync("src/routes/editor.$id.tsx","utf8");
assert.ok(e.includes('aria-label="Найти в заметке"'));
assert.ok(e.includes('noteSearchKey'));
assert.ok(e.includes('onClick={handleSave}'));
assert.ok(!i.includes('aria-label="Найти в заметке"'));
const st=readFileSync("src/routes/settings.tsx","utf8");
assert.ok(st.includes('<Section title="Редактор"'));
console.log("In-note search, exclusive compact menu, and editor settings checks passed.");
